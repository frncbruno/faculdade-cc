    private void jButtonCarregarArquivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCarregarArquivoActionPerformed
        StringBuilder dadosSessoes = new StringBuilder();

        if (!Utilidades.carregarArquivoEmHashMap(
                jTextFieldNomeArquivo.getText(),
                tabela.sessoes,
                dadosSessoes)) {

            JOptionPane.showMessageDialog(this, "Arquivo não localizado ou com problemas!");
            return;
        }

        jTextAreaDadosSessoes.setText(dadosSessoes.toString());

        jTextAreaDadosSessoes.setEnabled(true);
        jTextAreaDadosSessoes.setEditable(false);
        jTextAreaDadosSessoes.setFocusable(true);

        JOptionPane.showMessageDialog(this, "Arquivo carregado com sucesso!");
    }//GEN-LAST:event_jButtonCarregarArquivoActionPerformed

    private void jButtonEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarActionPerformed
        String numero = JOptionPane.showInputDialog(this,
                "Digite o número do celular:");

        if (numero == null || numero.trim().isEmpty()) {
            return;
        }

        Sessao sessao = tabela.sessoes.get(numero.trim());

        if (sessao != null) {
            jTextAreaDadosSessoes.setText(sessao.toString());
        } else {
            JOptionPane.showMessageDialog(this,
                    "Número não encontrado!");
        }
    }//GEN-LAST:event_jButtonEditarActionPerformed

